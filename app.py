"""
app.py

Interactive Streamlit dashboard for GridSense ML.
Visualizes holdout predictions, regression metrics, peak classification
performance, and model feature importances using Plotly.
"""

import json
from pathlib import Path
from typing import Any, Dict, Tuple

import pandas as pd
import plotly.express as px
import plotly.graph_objects as go
import streamlit as st

# --- Configuration & Styling ---
st.set_page_config(
    page_title="GridSense ML Dashboard",
    page_icon="⚡",
    layout="wide",
    initial_sidebar_state="expanded",
)

ARTIFACT_DIR = Path("artifacts/metrics")


# --- Data Loading (Cached) ---
@st.cache_data
def load_artifacts() -> Tuple[pd.DataFrame, pd.DataFrame, Dict[str, Any], Dict[str, Any]]:
    """Loads all evaluation artifacts generated by train_pipeline.py."""
    if not ARTIFACT_DIR.exists():
        st.error(f"Artifact directory not found at {ARTIFACT_DIR}. Run `python train_pipeline.py` first.")
        st.stop()

    try:
        leaderboard = pd.read_csv(ARTIFACT_DIR / "model_leaderboard.csv")
        predictions = pd.read_parquet(ARTIFACT_DIR / "holdout_predictions.parquet")
        
        with open(ARTIFACT_DIR / "feature_importances.json", "r") as f:
            importances = json.load(f)
            
        with open(ARTIFACT_DIR / "peak_threshold.json", "r") as f:
            peak_info = json.load(f)
            
        return leaderboard, predictions, importances, peak_info
    
    except FileNotFoundError as e:
        st.error(f"Missing artifact file: {e}. Please re-run the training pipeline.")
        st.stop()


# --- Plotting Helpers ---
def plot_forecast_timeline(
    df: pd.DataFrame, 
    model_name: str, 
    peak_threshold: float,
    max_points: int = 1500
) -> go.Figure:
    """Plots actuals vs. predictions over time with a peak threshold line."""
    # Slice the last N points for better UI performance and visibility
    plot_df = df.iloc[-max_points:].copy()
    pred_col = f"pred_{model_name}"

    fig = go.Figure()
    fig.add_trace(
        go.Scatter(
            x=plot_df.index, y=plot_df["actual_wh"], 
            name="Actual (Wh)", line=dict(color="#1f77b4", width=2), opacity=0.8
        )
    )
    fig.add_trace(
        go.Scatter(
            x=plot_df.index, y=plot_df[pred_col], 
            name=f"Predicted ({model_name})", line=dict(color="#ff7f0e", width=2, dash="dot"), opacity=0.9
        )
    )
    fig.add_hline(
        y=peak_threshold, 
        line_dash="dash", line_color="red", 
        annotation_text="Peak Demand Threshold", 
        annotation_position="top left"
    )
    
    fig.update_layout(
        title="Short-Term Forecast vs Actual Load (Holdout Segment)",
        xaxis_title="Time",
        yaxis_title="Energy Consumption (Wh)",
        hovermode="x unified",
        template="plotly_white",
        legend=dict(orientation="h", yanchor="bottom", y=1.02, xanchor="right", x=1)
    )
    return fig


def plot_feature_importance(importances_dict: Dict[str, Any], model_name: str) -> go.Figure:
    """Renders a horizontal bar chart of the top features for the selected model."""
    if model_name not in importances_dict:
        fig = go.Figure()
        fig.update_layout(title="Feature Importances Not Available for this Model")
        return fig

    df_imp = pd.DataFrame(importances_dict[model_name])
    df_imp = df_imp.sort_values(by="importance_pct", ascending=True).tail(15)  # Top 15

    fig = px.bar(
        df_imp, x="importance_pct", y="feature", orientation="h",
        title="Top 15 Predictive Features",
        labels={"importance_pct": "Importance (%)", "feature": ""},
        color="importance_pct", color_continuous_scale="Blues"
    )
    fig.update_layout(template="plotly_white", showlegend=False, coloraxis_showscale=False)
    return fig


def plot_hourly_error(df: pd.DataFrame, model_name: str) -> go.Figure:
    """Plots average MAE by hour of the day to detect diurnal error patterns."""
    pred_col = f"pred_{model_name}"
    
    temp = df[["actual_wh", pred_col]].copy()
    temp["hour"] = temp.index.hour
    temp["abs_err"] = (temp["actual_wh"] - temp[pred_col]).abs()
    
    hourly_mae = temp.groupby("hour")["abs_err"].mean().reset_index()

    fig = px.bar(
        hourly_mae, x="hour", y="abs_err",
        title="Mean Absolute Error (MAE) by Hour of Day",
        labels={"hour": "Hour of Day (0-23)", "abs_err": "MAE (Wh)"}
    )
    fig.update_layout(
        template="plotly_white", 
        xaxis=dict(tickmode="linear", tick0=0, dtick=1)
    )
    return fig


# --- App Layout & Logic ---
def main():
    st.title("⚡ GridSense ML: Load Forecasting & Peak Intelligence")
    
    # Load Data
    leaderboard_df, preds_df, importances_dict, peak_info = load_artifacts()
    available_models = leaderboard_df["model"].tolist()
    threshold_wh = peak_info.get("threshold_wh", 0.0)

    # Sidebar Controls
    st.sidebar.header("Control Panel")
    selected_model = st.sidebar.selectbox("Inspect Model", available_models)
    
    st.sidebar.markdown("---")
    st.sidebar.subheader("Peak Analytics Info")
    st.sidebar.metric("Fitted Peak Threshold", f"{threshold_wh:.1f} Wh")
    st.sidebar.caption(f"Derived from {peak_info.get('quantile', 0.9)*100:.0f}th percentile of training data.")

    # Main Dashboard
    model_stats = leaderboard_df[leaderboard_df["model"] == selected_model].iloc[0]

    # Row 1: High-Level Metrics
    st.subheader(f"Performance: {selected_model}")
    col1, col2, col3, col4 = st.columns(4)
    with col1:
        st.metric("Holdout RMSE", f"{model_stats['test_rmse']:.2f} Wh")
    with col2:
        st.metric("Holdout MAE", f"{model_stats['test_mae']:.2f} Wh")
    with col3:
        st.metric("R² Score", f"{model_stats['test_r2']:.3f}")
    with col4:
        st.metric("Peak Detection F1", f"{model_stats.get('peak_f1', 0.0):.3f}")

    st.markdown("---")

    # Row 2: Time Series Chart
    st.plotly_chart(
        plot_forecast_timeline(preds_df, selected_model, threshold_wh), 
        use_container_width=True
    )

    # Row 3: Feature Importance & Hourly Diagnostics
    st.markdown("---")
    col_feat, col_err = st.columns(2)
    
    with col_feat:
        st.plotly_chart(plot_feature_importance(importances_dict, selected_model), use_container_width=True)
        
    with col_err:
        st.plotly_chart(plot_hourly_error(preds_df, selected_model), use_container_width=True)
        
    # Row 4: Full Leaderboard Table
    st.markdown("---")
    st.subheader("Leaderboard (All Models)")
    st.dataframe(
        leaderboard_df.style.highlight_min(subset=["test_rmse", "test_mae"], color="lightgreen")
                      .highlight_max(subset=["test_r2", "peak_f1"], color="lightgreen"),
        use_container_width=True
    )

if __name__ == "__main__":
    main()